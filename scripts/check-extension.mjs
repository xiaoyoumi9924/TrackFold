import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const browser = await chromium.launch({ headless: true, executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
try {
  const page = await browser.newPage({ viewport: { width: 1200, height: 800 } });
  await page.goto('https://example.com');
  await page.setContent(`<style>body { margin: 0; background: #151722 } .player { position: absolute; top: 90px; left: 180px; width: 1000px; height: 650px; background: #33493c } video { width: 100%; height: 100% } .off { top: 850px }</style><div class="player" data-e2e="feed-active-video" data-e2e-vid="1111111111111111111"><video></video></div><div class="player off" data-e2e="feed-video" data-e2e-vid="2222222222222222222"><video></video></div>`);
  await page.addStyleTag({ content: await readFile('browser-extension/content.css', 'utf8') });
  await page.evaluate(() => { window.captured = []; HTMLAnchorElement.prototype.click = function () { window.captured.push(this.href); }; });
  await page.addScriptTag({ content: await readFile('browser-extension/content.js', 'utf8') });
  const button = page.getByRole('button', { name: '选择保存音频或视频' });
  const menu = page.getByRole('group', { name: '选择保存类型' });
  await button.waitFor({ state: 'visible' });
  const box = await button.boundingBox();
  assert.ok(box.x > 1000 && box.y >= 90 && box.y < 140, `unexpected position ${JSON.stringify(box)}`);
  await button.focus();
  await page.keyboard.press('Enter');
  assert.equal(await button.getAttribute('aria-expanded'), 'true');
  await menu.waitFor({ state: 'visible' });
  await page.screenshot({ path: '/tmp/shiyin-combined-menu.png' });
  await page.keyboard.press('Escape');
  assert.equal(await button.getAttribute('aria-expanded'), 'false');
  assert.equal(await button.evaluate(el => el === document.activeElement), true);
  await button.click();
  await menu.getByRole('button', { name: '保存音频' }).click();
  assert.equal(await page.evaluate(() => window.captured.at(-1)), 'shiyin-audio://douyin/download?id=1111111111111111111');
  await button.click();
  await menu.getByRole('button', { name: '保存视频' }).click();
  assert.equal(await page.evaluate(() => window.captured.at(-1)), 'shiyin-audio://douyin/video?id=1111111111111111111');
  await button.click();
  await menu.getByRole('button', { name: '保存音频' }).click();
  assert.equal(await page.evaluate(() => window.captured.length), 2);
  assert.match(await page.locator('.shiyin-audio-notice').innerText(), /已尝试打开/);
  await button.click();
  await page.evaluate(() => {
    const a = document.querySelector('[data-e2e="feed-active-video"]');
    const b = document.querySelector('[data-e2e="feed-video"]');
    a.setAttribute('data-e2e', 'feed-video'); a.classList.add('off');
    b.setAttribute('data-e2e', 'feed-active-video'); b.classList.remove('off');
  });
  await page.waitForFunction(() => document.querySelector('#shiyin-save-options').hidden);
  await button.click();
  await menu.getByRole('button', { name: '保存音频' }).click();
  assert.equal(await page.evaluate(() => window.captured.at(-1)), 'shiyin-audio://douyin/download?id=2222222222222222222');
  await button.click();
  await page.evaluate(() => document.querySelector('[data-e2e="feed-active-video"]').removeAttribute('data-e2e-vid'));
  await menu.getByRole('button', { name: '保存视频' }).click();
  assert.equal(await page.evaluate(() => window.captured.length), 3);
  console.log('PASS combined menu, keyboard, both choices, duplicates, video switch and unknown ID');
} finally { await browser.close(); }
