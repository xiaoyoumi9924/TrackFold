import { _electron } from 'playwright';
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import os from 'node:os';
const executablePath=path.resolve(process.env.SHIYIN_TEST_EXECUTABLE || 'release/unified-runtime/mac-arm64/拾音.app/Contents/MacOS/拾音');
const ffmpeg=path.resolve(executablePath,'../../Resources/bin/ffmpeg');
const ffprobe=path.resolve(executablePath,'../../Resources/bin/ffprobe');
const root=mkdtempSync(path.join(os.tmpdir(),'shiyin-queue-'));
const files=Array.from({length:12}, (_, index)=>path.join(root, `队列${index + 1}.wav`));
for (const [i,file] of files.entries()) execFileSync(ffmpeg,['-v','error','-f','lavfi','-i',`sine=frequency=${400+i*200}:duration=4`,file]);
const originals=files.map(file=>readFileSync(file)); let app;
try {
 app=await _electron.launch({executablePath, args:[], env:{...process.env, SHIYIN_DESKTOP_DATA_DIR:path.join(root,'profile'), SHIYIN_DESKTOP_OUTPUT_DIR:path.join(root,'output')},timeout:45000});
 const page=await app.firstWindow(); const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.locator('main').waitFor();
 assert.equal(await page.evaluate(()=>localStorage.getItem('shiyin-format')),'mp3');
 await page.getByRole('button',{name:'任务',exact:true}).click();
 await page.getByRole('button',{name:'队列操作',exact:true}).click();
 await page.getByRole('button',{name:'暂停后续任务'}).click();
 await page.getByText(/音频队列.*已暂停/).waitFor();
 await page.getByRole('button',{name:'音频提取',exact:true}).click();
 await page.getByRole('tab',{name:'本地文件',exact:true}).click();
 await page.locator('.upload-entry input[type=file]').setInputFiles(files);
 const panel=page.locator('.local-batch-panel');
 assert.equal(await panel.getByLabel('输出格式',{exact:true}).inputValue(),'mp3');
 await panel.getByRole('button',{name:'保存所选 12 个',exact:true}).click();
 await page.waitForFunction(async()=> (await (await fetch('/api/jobs')).json()).length===12);
 await page.getByRole('button',{name:'任务',exact:true}).click();
 await page.getByRole('button',{name:'队列操作',exact:true}).click();
 await page.getByText('12 项音频等待中', {exact:true}).waitFor();
 let jobs=await page.evaluate(async()=>await (await fetch('/api/jobs')).json());
 assert(jobs.every(j=>j.status==='queued' && j.format==='mp3'));
 const cancelledId=jobs[0].id;
 await page.locator('.job-row').filter({hasText:jobs[0].title}).getByRole('button',{name:'取消任务'}).click();
 await page.getByText('11 项音频等待中',{exact:true}).waitFor();
 const resumeResponse=page.waitForResponse(response=>response.url().endsWith('/api/queue') && response.request().method()==='POST');
 await page.getByRole('button',{name:'继续队列'}).click();
 const started=await (await resumeResponse).json();
 assert.equal(started.limit,10);
 assert.equal(started.active,10);
 assert.equal(started.waiting,1);
 for (let i=0;i<100;i++) { jobs=await page.evaluate(async()=>await (await fetch('/api/jobs')).json()); if (jobs.filter(j=>j.status==='completed').length===11) break; await new Promise(r=>setTimeout(r,100)); }

 assert.equal(jobs.find(j=>j.id===cancelledId).status,'cancelled');
 assert.equal(jobs.filter(j=>j.status==='completed').length,11);
 const done=jobs.find(j=>j.status==='completed');
 assert.equal(done.format,'mp3'); assert(done.filePath.endsWith('.mp3'));
 execFileSync(ffmpeg,['-v','error','-i',done.filePath,'-f','null','-']);
 assert.equal(execFileSync(ffprobe,['-v','error','-select_streams','a:0','-show_entries','stream=codec_name','-of','default=noprint_wrappers=1:nokey=1',done.filePath],{encoding:'utf8'}).trim(),'mp3');
 await page.getByRole('button',{name:'歌单',exact:true}).click();
 await page.getByRole('button',{name:'更多歌曲操作',exact:true}).first().click();
 await page.getByRole('button',{name:'截取音频片段',exact:true}).click();
 assert.equal(await page.getByLabel('导出格式').inputValue(),'mp3');
 await page.keyboard.press('Escape');
 await page.setViewportSize({width:390,height:900});
 await page.getByRole('button',{name:'任务',exact:true}).click();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.screenshot({path:'/tmp/shiyin-queue-mp3-mobile.png',fullPage:true});
 assert(originals.every((bytes,i)=>bytes.equals(readFileSync(files[i])))); assert.deepEqual(errors,[]);
 console.log('PASS packaged app: ten active audio jobs, overflow waiting, cancellation, resume, valid MP3, mobile layout');
} catch (e) { console.error(e); throw e; } finally {if(app) {const closed=app.waitForEvent('close'); await app.evaluate(({app})=>app.quit()); await closed;}}
