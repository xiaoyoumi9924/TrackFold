import { _electron } from 'playwright';
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, existsSync, renameSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import os from 'node:os';
const executablePath = path.resolve(process.env.SHIYIN_TEST_EXECUTABLE || 'release/unified-runtime/mac-arm64/拾音.app/Contents/MacOS/拾音');
const ffmpeg = path.resolve(executablePath, '../../Resources/bin/ffmpeg');
const root = mkdtempSync(path.join(os.tmpdir(), 'shiyin-export-desktop-'));
const files = ['一.wav', '二.wav'].map(name => path.join(root, name));
for (const [i, file] of files.entries()) execFileSync(ffmpeg, ['-v','error','-f','lavfi','-i',`sine=frequency=${400+i*100}:duration=3`,file]);
const originals = files.map(file => readFileSync(file));
let app;
try {
 app = await _electron.launch({executablePath, args:[], env:{...process.env, SHIYIN_DESKTOP_DATA_DIR:path.join(root,'profile'), SHIYIN_DESKTOP_OUTPUT_DIR:path.join(root,'output')}, timeout:45000});
 const page = await app.firstWindow(); const errors=[]; page.on('pageerror', e => errors.push(e.message));
 await page.locator('main').waitFor();
 await page.getByRole('tab',{name:'本地文件',exact:true}).click();
 await page.locator('.upload-entry input[type=file]').setInputFiles(files);
 const panel=page.locator('.local-batch-panel');
 await panel.getByRole('button',{name:'保存所选 2 个',exact:true}).click();
 await page.waitForFunction(() => document.querySelector('.local-batch-panel')?.innerText.includes('本批已完成 2 个'), null, {timeout:90000});
 await page.getByRole('button',{name:'歌单',exact:true}).click();
 await page.getByRole('button',{name:'筛选',exact:true}).click();
 await page.getByRole('button',{name:'多选'}).click();
 await page.getByRole('checkbox',{name:'全选',exact:true}).check();
 await page.getByText('已选 2 首', {exact:false}).waitFor();
 await page.getByRole('button',{name:'导出播放列表'}).click();
 await page.getByText('已导出 2 首', {exact:false}).waitFor();
 const list = path.join(root,'output','拾音播放列表.m3u8');
 const content = readFileSync(list,'utf8');
 const paths = content.split('\n').filter(line => line.startsWith('/'));
 assert.equal(paths.length,2); assert(paths.every(existsSync));
 for (const file of paths) execFileSync(ffmpeg,['-v','error','-i',file,'-f','null','-']);
 await page.getByRole('button',{name:'导出歌曲清单'}).click();
 await page.getByRole('status').filter({ hasText: '歌曲清单.txt' }).waitFor();
 assert.match(readFileSync(path.join(root,'output','拾音歌曲清单.txt'),'utf8'), /一/);
 await page.getByRole('button',{name:'导出分享文件夹'}).click();
 await page.getByRole('status').filter({ hasText: '已导出分享文件夹' }).waitFor();
 const bundle=path.join(root,'output','拾音分享'), moved=path.join(root,'已移动的歌曲包'); renameSync(bundle,moved);
 const relative=readFileSync(path.join(moved,'播放列表.m3u8'),'utf8').split('\n').filter(line=>line.startsWith('./'));
 assert.equal(relative.length,2); for (const item of relative) { const file=path.resolve(moved,item); assert(existsSync(file)); execFileSync(ffmpeg,['-v','error','-i',file,'-f','null','-']); }
 assert(originals.every((bytes,i) => bytes.equals(readFileSync(files[i]))));
 await page.setViewportSize({width:390,height:900});
 assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
 await page.screenshot({path:'/tmp/shiyin-export-mobile.png',fullPage:true});
 assert.deepEqual(errors,[]);
 console.log('PASS packaged app: selection, portable share folder after moving, valid audio copies, playlist and song list, narrow layout');
} finally { if(app) {const closed=app.waitForEvent('close'); await app.evaluate(({app})=>app.quit()); await closed;} }
